import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import {
  ContentService,
  attachReference,
  createCard,
  parseReferenceFile,
  InMemoryCardRepository,
  InMemoryDeckRepository,
  InMemoryLanguageRepository,
  parseCardFile,
  seedCards,
  seedDecks,
  seedLanguages,
  type Card,
  type ReferenceFile,
} from "@ogbifo/domain";
import { devReference, devReferenceAudioUrl, isDevReferenceCard } from "./dev-reference";

/**
 * D-012: users see only reviewed Cards. The developer seed is unreviewed, so
 * it shows only in development or when OGBIFO_ALLOW_UNREVIEWED=1 (see
 * .env.example). Static pages read this at build time.
 */
export const allowUnreviewed =
  process.env.NODE_ENV === "development" || process.env.OGBIFO_ALLOW_UNREVIEWED === "1";

function loadReferenceFiles(): Map<string, ReferenceFile> {
  const dir = join(process.cwd(), "content", "references");
  const files = new Map<string, ReferenceFile>();
  if (!existsSync(dir)) return files;
  for (const name of readdirSync(dir).filter((f) => f.endsWith(".json"))) {
    try {
      const parsed = parseReferenceFile(JSON.parse(readFileSync(join(dir, name), "utf8")));
      if (parsed.ok) files.set(parsed.value.cardId, parsed.value);
      else console.error(`Skipping reference file ${name}: ${parsed.error.message}`);
    } catch (error) {
      console.error(`Skipping unreadable reference file ${name}`, error);
    }
  }
  return files;
}

/**
 * Cards exported from a reviewed sheet (`npm run cards -- export`). Read from
 * OGBIFO_CARDS_DIR or content/cards. They are private (gitignored); a file that
 * fails validation is reported and skipped, never half-applied.
 */
function loadSheetCards(): Card[] {
  const dir = process.env.OGBIFO_CARDS_DIR ?? join(process.cwd(), "content", "cards");
  const cards: Card[] = [];
  if (!existsSync(dir)) return cards;
  for (const name of readdirSync(dir).filter((f) => f.endsWith(".json"))) {
    try {
      const parsed = parseCardFile(JSON.parse(readFileSync(join(dir, name), "utf8")));
      for (const r of parsed.rejected) console.error(`Card ${r.id} in ${name} rejected: ${r.reason}`);
      cards.push(...parsed.cards);
    } catch (error) {
      console.error(`Skipping unreadable Card file ${name}`, error);
    }
  }
  return cards;
}

/** Seed Cards (developer content) overridden by sheet Cards with the same id, plus the rest. */
function allCards(): Card[] {
  const byId = new Map<string, Card>(seedCards.map((c) => [c.id, c]));
  for (const c of loadSheetCards()) byId.set(c.id, c);
  return [...byId.values()];
}

/** Attach reference audio to Cards. A reference that fails validation is skipped, never half-applied. */
function withReferences(cards: readonly Card[]): Card[] {
  const files = loadReferenceFiles();
  return cards.map((card) => {
    const file = files.get(card.id);
    if (file) {
      const attached = attachReference(card, file);
      if (attached.ok) return attached.value;
      console.error(`Reference for ${card.id} rejected: ${attached.error.message}`);
      return card;
    }
    let candidate: Card | null = null;
    if (allowUnreviewed && isDevReferenceCard(card.id)) {
      const dev = devReference(card.id, card.sourceText);
      candidate = {
        ...card,
        referenceAudioUrl: devReferenceAudioUrl(card.id),
        referenceAnnotation: dev.annotation,
        referenceProvenance: {
          source: "Synthetic test voice generated by Ogbifọ. Not a Yorùbá voice.",
          licence: "synthetic_test",
          rightsHolder: "Ogbifọ",
          speakerConsent: false,
          recordedOn: "2026-10-17",
        },
      };
    }
    if (!candidate) return card;
    const checked = createCard(candidate);
    if (!checked.ok) {
      console.error(`Reference for ${card.id} rejected: ${checked.error.message}`);
      return card;
    }
    return checked.value;
  });
}

/**
 * Composition root. Pages depend on ContentService only. Swap the in-memory
 * repositories for database-backed ones here when the Postgres adapter lands;
 * no page changes.
 */
let service: ContentService | undefined;

export function getContentService(): ContentService {
  service ??= new ContentService(
    new InMemoryLanguageRepository(seedLanguages),
    new InMemoryDeckRepository(seedDecks),
    new InMemoryCardRepository(withReferences(allCards())),
    { allowUnreviewed },
  );
  return service;
}

export interface ReviewerCard {
  id: string;
  sourceText: string;
  languageCode: string;
  deckName: string;
}

/**
 * Every Card, reviewed or not, for the reviewer annotation tool. Reviewers work
 * on Cards that learners cannot see yet (D-012).
 */
export async function listCardsForReviewers(): Promise<ReviewerCard[]> {
  const all = new ContentService(
    new InMemoryLanguageRepository(seedLanguages),
    new InMemoryDeckRepository(seedDecks),
    new InMemoryCardRepository(allCards()),
    { allowUnreviewed: true },
  );
  const out: ReviewerCard[] = [];
  for (const { deck, language } of await all.listDeckSummaries()) {
    const detail = await all.getDeck(deck.id);
    if (!detail.ok) continue;
    for (const card of detail.value.cards) {
      out.push({ id: card.id, sourceText: card.sourceText, languageCode: language.code, deckName: deck.name });
    }
  }
  return out;
}
